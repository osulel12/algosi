"""
Дано: строка s, состоящая из строчных английских букв.
Нужно: посчитать количество её подстрок, в которых все символы различны.
Подстрока должна быть непрерывной. Например, ab — подстрока строки abc, а ac — уже нет.
Одинаковые по содержанию подстроки, стоящие на разных позициях, считаются отдельно.
Поэтому в строке abab подстрока ab встречается дважды и даёт два элемента в ответе.


Алгоритм решения
1. Создаём пустой словарь last_seen и ставим left = 0.
2. Двигаем правую границу right по строке.
3. Если s[right] уже встречался внутри текущего окна, переносим left на позицию после прошлого вхождения.
4. Записываем right как последнюю позицию текущего символа.
5. Прибавляем к ответу right - left + 1.
6. После обработки всей строки возвращаем накопленную сумму.



Сложность по памяти O(1)
Сложность по времени O(n)
"""


class Solution:
    def numberOfSpecialSubstrings(self, s: str) -> int:
        last_seen = {}
        left = 0
        answer = 0

        for right, char in enumerate(s):
            if char in last_seen:
                # Граница никогда не должна двигаться назад
                left = max(left, last_seen[char] + 1)

            last_seen[char] = right
            # Все суффиксы корректного окна тоже корректны
            answer += right - left + 1

        return answer


inst = Solution()
print(inst.numberOfSpecialSubstrings('abc'))
print(inst.numberOfSpecialSubstrings('abab'))
